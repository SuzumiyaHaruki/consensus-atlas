const etcdraftSemanticInputLimit = 256 << 10

// etcdraftSemanticAuthoringSource is an editable source, not a second sealed
// protocol contract. Loading it immediately constructs the existing trusted
// ProtocolKnowledgePack and TestHypothesis values.
type etcdraftSemanticAuthoringSource struct {
	Knowledge  controlexperiment.ProtocolKnowledgePack `json:"protocol_knowledge"`
	Hypothesis controlexperiment.TestHypothesis        `json:"test_hypothesis"`
	Workload   etcdraftWorkloadAuthoringSource         `json:"workload"`
	Experiment etcdraftAgentExperimentConfig           `json:"experiment"`
}

// etcdraftWorkloadAuthoringSource keeps the editable file free of the
// PayloadEnvelope digest generated by the target Adapter. Loading it produces
// the existing protocol-neutral WorkloadPlan consumed by execution.
type etcdraftWorkloadAuthoringSource struct {
	ID             string                                `json:"id"`
	TargetSelector string                                `json:"target_selector"`
	Invocations    []etcdraftWorkloadInvocationAuthoring `json:"invocations"`
}

type etcdraftWorkloadInvocationAuthoring struct {
	ID             string `json:"id"`
	Operation      string `json:"operation"`
	Value          string `json:"value"`
	ExpectedStatus string `json:"expected_status"`
}

func (source etcdraftWorkloadAuthoringSource) build() (controlexperiment.WorkloadPlan, error) {
	workload := controlexperiment.WorkloadPlan{
		SchemaVersion: controlexperiment.WorkloadPlanVersion,
		ID:            source.ID, TargetSelector: source.TargetSelector,
		Invocations: make([]controlexperiment.WorkloadInvocation, 0, len(source.Invocations)),
	}
	for _, invocation := range source.Invocations {
		payload, err := etcdraftv2.InputPayload(etcdraftv2.Input{
			Operation: invocation.Operation,
			RequestID: invocation.ID,
			Value:     []byte(invocation.Value),
		})
		if err != nil {
			return controlexperiment.WorkloadPlan{}, err
		}
		workload.Invocations = append(workload.Invocations, controlexperiment.WorkloadInvocation{
			ID: invocation.ID, Input: payload, ExpectedStatus: invocation.ExpectedStatus,
		})
	}
	if err := workload.Validate(); err != nil {
		return controlexperiment.WorkloadPlan{}, err
	}
	return workload, nil
}

// etcdraftAgentExperimentConfig contains only inputs already consumed by the
// active A2/A4 composition. It is authoring data, not a generic budget DSL.
type etcdraftAgentExperimentConfig struct {
	AdapterConfig            etcdraftv2.Config                              `json:"adapter_config"`
	Runtime                  controlexperiment.RuntimeConfig                `json:"runtime"`
	FaultEnvelope            controlexperiment.FaultEnvelope                `json:"fault_envelope"`
	SearchMaxDepth           int                                            `json:"search_max_depth"`
	SearchMaxWorkItems       int                                            `json:"search_max_work_items"`
	SearchMaxWorkUnits       int                                            `json:"search_max_work_units"`
	ExplorerBudget           controlexperiment.SemanticExplorerBudget       `json:"explorer_budget"`
	ScenarioMaxCalls         int                                            `json:"scenario_max_calls"`
	ScenarioMaxSteps         int                                            `json:"scenario_max_steps"`
	ScenarioMaxDecisions     int                                            `json:"scenario_max_decisions"`
	ScenarioSemanticExposure controlexperiment.ScenarioSemanticExposureMode `json:"scenario_semantic_exposure"`
	ModelReasoningEffort     string                                         `json:"model_reasoning_effort"`
	ModelExcludeReasoning    bool                                           `json:"model_exclude_reasoning"`
	ModelMaxOutputTokens     int                                            `json:"model_max_output_tokens"`
	ModelMaxRetries          int                                            `json:"model_max_retries"`
	SessionBudget            controlexperiment.CampaignLogicalBudget        `json:"session_budget"`
	SessionWallClockMS       int64                                          `json:"session_wall_clock_ms"`
}

func (config etcdraftAgentExperimentConfig) validate() error {
	seed, seedErr := hex.DecodeString(config.Runtime.SeedHex)
	_, adapterErr := etcdraftv2.NewWithConfig(config.AdapterConfig)
	if adapterErr != nil || seedErr != nil || len(seed) == 0 || config.Runtime.ClockError != 0 ||
		config.FaultEnvelope.Validate() != nil || config.SearchMaxDepth <= 0 ||
		config.SearchMaxWorkItems <= 0 || config.SearchMaxWorkUnits <= 0 ||
		config.ExplorerBudget.Validate() != nil || config.ScenarioMaxCalls <= 0 ||
		config.ScenarioMaxCalls > controlexperiment.ScenarioAgentMaxCalls ||
		config.ScenarioMaxSteps <= 0 || config.ScenarioMaxSteps > controlexperiment.ScenarioPlanMaxSteps ||
		config.ScenarioMaxDecisions <= 0 ||
		config.ScenarioMaxDecisions > controlexperiment.ScenarioAgentMaxDecisions ||
		config.ScenarioSemanticExposure.Validate() != nil ||
		!validOpenRouterReasoningEffort(config.ModelReasoningEffort) ||
		config.ModelMaxOutputTokens <= 0 || config.ModelMaxOutputTokens > 4096 ||
		config.ModelMaxRetries < 0 || config.ModelMaxRetries > 2 ||
		!validEtcdraftSessionBudget(config.SessionBudget, config.SessionWallClockMS) {
		return errors.New("ETCDRAFT_AGENT_EXPERIMENT_CONFIG_INVALID")
	}
	return nil
}

func validEtcdraftSessionBudget(
	budget controlexperiment.CampaignLogicalBudget,
	wallClockMS int64,
) bool {
	return budget.MaxAttempts > 0 && budget.MaxPrimarySchedulerDecisions > 0 &&
		budget.MaxPrimaryWorkUnits > 0 && budget.MaxReplayWorkUnits > 0 &&
		budget.MaxModelCalls > 0 && budget.MaxModelTokens > 0 && wallClockMS > 0
}

func (config etcdraftAgentExperimentConfig) faultEnvelope() *controlexperiment.FaultEnvelope {
	envelope := config.FaultEnvelope
	return &envelope
}

func loadEtcdraftSemanticAuthoringSource(
	path string,
	riskSpec semantic.RiskWitnessSpec,
) (
	controlexperiment.ProtocolKnowledgePack,
	controlexperiment.TestHypothesis,
	etcdraftAgentExperimentConfig,
	controlexperiment.WorkloadPlan,
	error,
) {
	var source etcdraftSemanticAuthoringSource
	if path == "" || riskSpec.Validate() != nil ||
		readStrictJSONFile(path, etcdraftSemanticInputLimit, &source) != nil {
		return controlexperiment.ProtocolKnowledgePack{}, controlexperiment.TestHypothesis{},
			etcdraftAgentExperimentConfig{}, controlexperiment.WorkloadPlan{},
			errors.New("ETCDRAFT_SEMANTIC_INPUT_FILE_INVALID")
	}
	if source.Knowledge.SchemaVersion != "" || source.Knowledge.Digest != "" ||
		source.Hypothesis.SchemaVersion != "" || source.Hypothesis.KnowledgeDigest != "" ||
		source.Hypothesis.RiskSpecDigest != "" || source.Hypothesis.Digest != "" ||
		source.Hypothesis.RiskID != riskSpec.RiskID {
		return controlexperiment.ProtocolKnowledgePack{}, controlexperiment.TestHypothesis{},
			etcdraftAgentExperimentConfig{}, controlexperiment.WorkloadPlan{},
			errors.New("ETCDRAFT_SEMANTIC_INPUT_AUTHORING_FIELDS_INVALID")
	}
	if source.Experiment.validate() != nil {
		return controlexperiment.ProtocolKnowledgePack{}, controlexperiment.TestHypothesis{},
			etcdraftAgentExperimentConfig{}, controlexperiment.WorkloadPlan{},
			errors.New("ETCDRAFT_SEMANTIC_INPUT_EXPERIMENT_INVALID")
	}
	workload, err := source.Workload.build()
	if err != nil {
		return controlexperiment.ProtocolKnowledgePack{}, controlexperiment.TestHypothesis{},
			etcdraftAgentExperimentConfig{}, controlexperiment.WorkloadPlan{},
			errors.New("ETCDRAFT_SEMANTIC_INPUT_WORKLOAD_INVALID")
	}
	knowledge, err := controlexperiment.NewProtocolKnowledgePack(source.Knowledge)
	if err != nil || knowledge.Family != riskSpec.FamilyID || knowledge.Protocol != "etcdraft" {
		return controlexperiment.ProtocolKnowledgePack{}, controlexperiment.TestHypothesis{},
			etcdraftAgentExperimentConfig{}, controlexperiment.WorkloadPlan{},
			errors.New("ETCDRAFT_SEMANTIC_INPUT_KNOWLEDGE_INVALID")
	}
	hypothesis, err := controlexperiment.NewTestHypothesis(
		source.Hypothesis.ID, knowledge, riskSpec, source.Hypothesis.Rationale,
		controlexperiment.SemanticBestFirstAlgorithmID,
	)
	if err != nil || hypothesis.Validate(
		knowledge, riskSpec, controlexperiment.ScenarioPlanningBackendID,
	) != nil {
		return controlexperiment.ProtocolKnowledgePack{}, controlexperiment.TestHypothesis{},
			etcdraftAgentExperimentConfig{}, controlexperiment.WorkloadPlan{},
			errors.New("ETCDRAFT_SEMANTIC_INPUT_HYPOTHESIS_INVALID")
	}
	return knowledge, hypothesis, source.Experiment, workload, nil
}
